-- Each year end rollover made on the sheet: the fiscal year rolled over, who made it and on which sheet-today,
-- whether it has been undone, the periods it generated, and the period it set opening balances for with the
-- amount it added to each person's, so the last one can be undone.
CREATE TABLE rollover (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id          VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    fy                INT           NOT NULL,
    made_by           VARCHAR(200)  NOT NULL,
    made_on           DATE          NOT NULL,
    opening_period_id BIGINT,
    undone            BOOLEAN       DEFAULT FALSE NOT NULL
);
CREATE INDEX rollover_sheet ON rollover (sheet_id, id);
CREATE TABLE rollover_period (
    rollover_id BIGINT NOT NULL REFERENCES rollover (id),
    period_id   BIGINT NOT NULL,
    PRIMARY KEY (rollover_id, period_id)
);
CREATE TABLE rollover_opening (
    rollover_id BIGINT         NOT NULL REFERENCES rollover (id),
    person_id   BIGINT         NOT NULL,
    amount      DECIMAL(15, 2) NOT NULL,
    PRIMARY KEY (rollover_id, person_id)
);
