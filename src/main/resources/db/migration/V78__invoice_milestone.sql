-- A draft billed by milestones: each a description and a percentage (over 0, together at most 100 and
-- exactly 100 to be sent) of what the client pays. Once sent a milestone is owed only from the day it
-- was reached; null while it is pending.
CREATE TABLE invoice_milestone (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT        NOT NULL REFERENCES invoice (id) ON DELETE CASCADE,
    description VARCHAR(255)  NOT NULL DEFAULT '',
    pct         DECIMAL(5, 2) NOT NULL,
    reached_on  DATE
);
