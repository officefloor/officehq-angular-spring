-- A statement can be taken as of a date: every change that moves a figure records the sheet's today
-- when it was made (made_on), so the figures can be rebuilt as they stood at the end of a date. A
-- record from before this has none and counts as made from the beginning of time.

-- Each rate set, in the order set: the grade, its from-date and to-date, the percent and when it was set.
CREATE TABLE rate_log (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100)  NOT NULL REFERENCES sheet (id),
    grade     VARCHAR(1)    NOT NULL,
    from_date DATE,
    to_date   DATE,
    pct       DECIMAL(5, 2) NOT NULL,
    made_on   DATE
);
CREATE INDEX rate_log_sheet ON rate_log (sheet_id, id);
INSERT INTO rate_log (sheet_id, grade, from_date, to_date, pct, made_on)
    SELECT sheet_id, grade, from_date, to_date, pct, NULL FROM rate;

-- Each setting value recorded, in the order recorded, and when.
CREATE TABLE sheet_setting_log (
    sheet_id    VARCHAR(100)   NOT NULL REFERENCES sheet (id),
    seq         INT            NOT NULL,
    setting_key VARCHAR(20)    NOT NULL,
    from_date   DATE,
    amount      DECIMAL(14, 2),
    made_on     DATE
);
CREATE INDEX sheet_setting_log_sheet ON sheet_setting_log (sheet_id);
INSERT INTO sheet_setting_log (sheet_id, seq, setting_key, from_date, amount, made_on)
    SELECT sheet_id, ROW_NUMBER() OVER (PARTITION BY sheet_id ORDER BY setting_key) - 1, setting_key, from_date,
        amount, NULL FROM sheet_setting;

