-- The sheet's notes: a text (trimmed, never blank), who added it and the sheet's today when it was
-- added. Under an as-of date the notes shown are those added while the sheet's today was on or before
-- it, so the notes are dated by added_on rather than kept in the sheet's history.
CREATE TABLE sheet_note (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    text     VARCHAR(2000) NOT NULL,
    added_by VARCHAR(100) NOT NULL,
    added_on DATE NOT NULL
);
CREATE INDEX sheet_note_sheet ON sheet_note (sheet_id);
