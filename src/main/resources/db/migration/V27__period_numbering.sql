-- The sheet's period numbering from-date: while set and the sheet's today is on or after it, a claim
-- opened is numbered within its period (<period name>-<n>), or X-<n> when in no period. None (blank)
-- means off: claims take the sheet-wide number (1, 2, ...), which continues where it left off.
ALTER TABLE sheet ADD COLUMN period_numbering_from DATE;
-- A claim's number, and the number a correction names, are now text: a sheet-wide number or a
-- period number.
ALTER TABLE claim ALTER COLUMN claim_number SET DATA TYPE VARCHAR(220);
ALTER TABLE claim ALTER COLUMN corrects_number SET DATA TYPE VARCHAR(220);
-- The last number given in each numbering sequence of a sheet other than the sheet-wide one: one per
-- prefix (a period's name, or X for claims in no period).
CREATE TABLE claim_sequence (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id    VARCHAR(200) NOT NULL REFERENCES sheet (id),
    prefix      VARCHAR(200) NOT NULL,
    last_number INT          NOT NULL
);
CREATE UNIQUE INDEX claim_sequence_prefix ON claim_sequence (sheet_id, prefix);
