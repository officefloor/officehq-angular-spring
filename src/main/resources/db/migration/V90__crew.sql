-- The sheet's crews: a name (trimmed, at most once on the sheet) and a lead chosen from the sheet's
-- people, and its members, each a person on the sheet at most once per crew and never its lead.
CREATE TABLE crew (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    name     VARCHAR(200) NOT NULL,
    lead_id  BIGINT NOT NULL REFERENCES person (id),
    CONSTRAINT crew_once UNIQUE (sheet_id, name)
);

CREATE TABLE crew_member (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL REFERENCES sheet (id),
    crew_id   BIGINT NOT NULL REFERENCES crew (id),
    person_id BIGINT NOT NULL REFERENCES person (id),
    CONSTRAINT crew_member_once UNIQUE (crew_id, person_id)
);
