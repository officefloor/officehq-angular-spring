-- The sheet's clerk limit: the largest due a clerk may settle (two decimals); none means no limit.
ALTER TABLE sheet ADD COLUMN clerk_limit DECIMAL(15, 2) CHECK (clerk_limit >= 0);

-- The role the sheet gives a user name: clerk or steward. A name with no row is a clerk.
CREATE TABLE sheet_role (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    user_name VARCHAR(200)  NOT NULL,
    role      VARCHAR(20)   NOT NULL CHECK (role IN ('clerk', 'steward'))
);
CREATE UNIQUE INDEX sheet_role_sheet_user ON sheet_role (sheet_id, user_name);
