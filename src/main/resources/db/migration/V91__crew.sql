-- The sheet's crews: a name (trimmed, once per sheet), a lead who is a person of the sheet, and members, each a
-- person of the sheet other than the lead, in a crew at most once. A person may be in several crews.
CREATE TABLE crew (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id       VARCHAR(200) NOT NULL REFERENCES sheet (id),
    name           VARCHAR(200) NOT NULL,
    lead_person_id BIGINT       NOT NULL REFERENCES person (id),
    UNIQUE (sheet_id, name)
);

CREATE TABLE crew_member (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id   BIGINT NOT NULL REFERENCES crew (id),
    person_id BIGINT NOT NULL REFERENCES person (id),
    UNIQUE (crew_id, person_id)
);
