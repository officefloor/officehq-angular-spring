-- The sheet's periods: a name, unique on the sheet without regard to case, and a from and to date,
-- both inclusive. No two periods on a sheet overlap (checked by the service, under the sheet's lock).
CREATE TABLE period (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL REFERENCES sheet (id),
    name      VARCHAR(100) NOT NULL,
    name_key  VARCHAR(100) GENERATED ALWAYS AS (LOWER(name)),
    from_date DATE         NOT NULL,
    to_date   DATE         NOT NULL,
    CHECK (from_date <= to_date)
);
CREATE UNIQUE INDEX period_sheet_name ON period (sheet_id, name_key);
CREATE INDEX period_sheet_from ON period (sheet_id, from_date);
