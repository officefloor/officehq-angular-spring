-- A period on the sheet: a name, unique on the sheet without regard to case, and a from and to date,
-- both inclusive. No two of a sheet's periods overlap (the service refuses one that would).
CREATE TABLE period (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    name      VARCHAR(200)  NOT NULL,
    name_key  VARCHAR(200)  GENERATED ALWAYS AS (LOWER(name)),
    from_date DATE          NOT NULL,
    to_date   DATE          NOT NULL,
    CHECK (from_date <= to_date)
);
CREATE UNIQUE INDEX period_sheet_name ON period (sheet_id, name_key);
