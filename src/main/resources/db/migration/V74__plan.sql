-- A person's plans: an amount, a start date, every N days (N at least 1) and an end date never before
-- the start. Generating makes a DRAFT claim for each plan date (the start, then every N days) up to
-- the end and the sheet's today; plan_date keeps each date a plan has made its claim for, so a date
-- is made once, and a date the claim form refused is tried again next time.
CREATE TABLE plan (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id   VARCHAR(100) NOT NULL REFERENCES sheet (id),
    person_id  BIGINT NOT NULL,
    amount     NUMERIC(14, 2) NOT NULL,
    start_date DATE NOT NULL,
    every_days INT NOT NULL CHECK (every_days >= 1),
    end_date   DATE NOT NULL,
    CONSTRAINT plan_dates CHECK (end_date >= start_date)
);

CREATE TABLE plan_date (
    plan_id    BIGINT NOT NULL REFERENCES plan (id),
    claim_date DATE NOT NULL,
    PRIMARY KEY (plan_id, claim_date)
);
