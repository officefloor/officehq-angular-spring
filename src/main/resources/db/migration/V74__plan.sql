-- A person's plan: an amount, made a DRAFT claim every so many days from its start to its end. The plan
-- dates it has made a claim for are kept, so generating again makes none for them; a date the claim form
-- refused is not kept, and is tried again next time.
CREATE TABLE plan (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id   VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    person_id  BIGINT        NOT NULL,
    amount     NUMERIC(15,2) NOT NULL,
    start_date DATE          NOT NULL,
    every_days INT           NOT NULL,
    end_date   DATE          NOT NULL
);
CREATE INDEX plan_sheet ON plan (sheet_id);

CREATE TABLE plan_generated (
    plan_id BIGINT NOT NULL REFERENCES plan (id),
    on_date DATE   NOT NULL,
    PRIMARY KEY (plan_id, on_date)
);
