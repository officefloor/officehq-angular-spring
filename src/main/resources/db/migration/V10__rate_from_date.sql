-- A rate can carry a from-date: a grade may have several rates, each in force from its from-date
-- until the next one's. A rate with no from-date applies from the beginning of time. A grade has at
-- most one rate per from-date (and at most one with none).
CREATE TABLE rate_dated (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL REFERENCES sheet (id),
    grade     VARCHAR(1)   NOT NULL,
    from_date DATE,
    rate      DECIMAL(5, 2) NOT NULL CHECK (rate >= 0),
    CONSTRAINT rate_sheet_grade_from UNIQUE NULLS NOT DISTINCT (sheet_id, grade, from_date)
);
INSERT INTO rate_dated (sheet_id, grade, from_date, rate) SELECT sheet_id, grade, NULL, rate FROM rate;
DROP TABLE rate;
ALTER TABLE rate_dated RENAME TO rate;
