-- A rate can carry a from-date: a grade may have several rates, one per from-date, and a rate with
-- no from-date applies from the beginning of time. A claim uses its grade's rate with the latest
-- from-date on or before the claim's date; a claim dated before every such rate has no rate.
-- Each row gets its own id; from_key stands for the from-date (no from-date counting as the
-- earliest date) so a grade has at most one rate per from-date.
ALTER TABLE rate ADD COLUMN from_date DATE;
ALTER TABLE rate ADD COLUMN from_key DATE GENERATED ALWAYS AS (COALESCE(from_date, DATE '0001-01-01'));
ALTER TABLE rate ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE rate DROP PRIMARY KEY;
ALTER TABLE rate ADD PRIMARY KEY (id);
ALTER TABLE rate ADD CONSTRAINT rate_grade_from_unique UNIQUE (sheet_id, grade, from_key);
