-- Dated changes to a region's tax rate: from a date on, the region's invoices are taxed at the new
-- rate. An invoice is taxed at the latest change on or before its issue date (a credit note at its
-- original's), or the standing region_tax_rate_<region> setting before any.
CREATE TABLE tax_rate_change (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region    VARCHAR(64)    NOT NULL,
    from_date DATE           NOT NULL,
    rate      DECIMAL(9, 4)  NOT NULL
);
