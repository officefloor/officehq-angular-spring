-- A statement taken of a person: the sheet's today when it was taken, the person's due-total then
-- (none when it showed n/a) and how many of their claims counted. Listed in the order taken (by id).
CREATE TABLE statement (
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id    VARCHAR(200)   NOT NULL REFERENCES sheet (id),
    person_id   BIGINT         NOT NULL REFERENCES person (id),
    taken_on    DATE           NOT NULL,
    due_total   DECIMAL(15, 2),
    claim_count INT            NOT NULL
);
CREATE INDEX statement_person ON statement (person_id, id);

-- A claim bound by its person's last statement shows and totals the figure it had then (none when
-- that was n/a), whatever later rate or grade changes would make it, until the next statement.
ALTER TABLE claim ADD COLUMN stated BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE claim ADD COLUMN stated_due DECIMAL(15, 2);
