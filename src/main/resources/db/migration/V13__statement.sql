-- A person's statements: each records the sheet's today when it was taken, the person's due-total
-- then (none when it was n/a) and how many of their claims counted. Listed oldest first (by id).
CREATE TABLE statement (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id   VARCHAR(100)   NOT NULL REFERENCES sheet (id),
    person_id  BIGINT         NOT NULL REFERENCES person (id),
    taken_on   DATE           NOT NULL,
    due_total  DECIMAL(14, 2),
    claims     INT            NOT NULL
);
CREATE INDEX statement_sheet ON statement (sheet_id, person_id, id);
-- A claim bound by its person's last statement: it shows and totals the figure it had then (none
-- when it had no rate then) until the next statement rebinds or unbinds it.
ALTER TABLE claim ADD COLUMN stated BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE claim ADD COLUMN stated_due DECIMAL(14, 2);
