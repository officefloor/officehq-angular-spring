-- A person's snapshot lines: one per SNAPSHOT written for them as the sheet's today moved on, with the day
-- being left and their due-total on it as shown ('n/a' when none). Listed in the order they were written.
CREATE TABLE person_snapshot (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL,
    person_id BIGINT       NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    snapshot_day DATE         NOT NULL,
    due_total VARCHAR(30)  NOT NULL
);
CREATE INDEX person_snapshot_sheet ON person_snapshot (sheet_id);
