-- The sheet's rate for each grade: a percent (0.00 or more, two decimals). A grade with no row has
-- no rate.
CREATE TABLE rate (
    id       BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    grade    VARCHAR(1)    NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    rate     DECIMAL(9, 2) NOT NULL CHECK (rate >= 0)
);
CREATE UNIQUE INDEX rate_sheet_grade ON rate (sheet_id, grade);
