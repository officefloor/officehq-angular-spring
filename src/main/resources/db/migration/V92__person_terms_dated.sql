-- A person's own terms can be dated: besides the terms they have from the beginning of time (person.terms),
-- each row here records terms (none: no terms of their own) from a date. On a date the terms in force are
-- those whose from-date is the latest on or before it, else those from the beginning of time.
CREATE TABLE person_terms (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person (id),
    terms     INTEGER,
    from_date DATE   NOT NULL
);
CREATE UNIQUE INDEX person_terms_from ON person_terms (person_id, from_date);
