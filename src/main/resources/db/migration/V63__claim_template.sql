-- The sheet's claim templates: a name (once per sheet), and the amount and note a claim made from it takes
-- at that moment. Saving a name again replaces its amount and note; claims made from it keep theirs.
CREATE TABLE claim_template (
    id       BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    name     VARCHAR(200)  NOT NULL,
    amount   NUMERIC(15,2) NOT NULL,
    note     VARCHAR(1000) NOT NULL,
    UNIQUE (sheet_id, name)
);
