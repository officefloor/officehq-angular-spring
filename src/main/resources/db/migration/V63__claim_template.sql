-- The sheet's claim templates: a name (trimmed, at most once on the sheet), an amount and a note.
-- Saving a name again replaces its amount and note. A claim made from a template copies them, so
-- a later change to the template leaves the claim as it was.
CREATE TABLE claim_template (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    name     VARCHAR(200) NOT NULL,
    amount   NUMERIC(14, 2) NOT NULL,
    note     VARCHAR(1000) NOT NULL,
    CONSTRAINT claim_template_once UNIQUE (sheet_id, name)
);
