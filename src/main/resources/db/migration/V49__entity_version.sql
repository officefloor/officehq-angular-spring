-- Each change to a sheet, its people, their claims and its rates keeps the state it left the row in, with
-- the sheet's today when it was made (none for a row removed), so a statement can be taken as of a date:
-- the rows as the changes made while the sheet's today was on or before it left them. Oldest first (by id).
-- Rows changed before this was kept have no versions.
CREATE TABLE entity_version (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id    VARCHAR(200) NOT NULL,
    kind        VARCHAR(20)  NOT NULL,
    entity_id   VARCHAR(200) NOT NULL,
    recorded_on DATE         NOT NULL,
    state       CLOB
);
CREATE INDEX entity_version_sheet ON entity_version (sheet_id, kind, recorded_on);
