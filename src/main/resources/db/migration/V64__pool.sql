-- The sheet's pools: a name (trimmed, once per sheet) and members, each a person of the sheet with a share
-- percent (more than 0.00, at most 100.00). A person is in a pool at most once, and may be in several pools.
CREATE TABLE pool (
    id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(200) NOT NULL REFERENCES sheet (id),
    name     VARCHAR(200) NOT NULL,
    UNIQUE (sheet_id, name)
);

CREATE TABLE pool_member (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id   BIGINT       NOT NULL REFERENCES pool (id),
    person_id BIGINT       NOT NULL REFERENCES person (id),
    share     NUMERIC(5,2) NOT NULL CHECK (share > 0 AND share <= 100),
    UNIQUE (pool_id, person_id)
);
