-- The sheet's pools: a name (trimmed, at most once on the sheet) and its members, each a person on
-- the sheet at most once per pool with a share percent. A person may be in several pools.
CREATE TABLE pool (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    name     VARCHAR(200) NOT NULL,
    CONSTRAINT pool_once UNIQUE (sheet_id, name)
);

CREATE TABLE pool_member (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id   BIGINT NOT NULL REFERENCES pool (id),
    person_id BIGINT NOT NULL REFERENCES person (id),
    share     NUMERIC(5, 2) NOT NULL,
    CONSTRAINT pool_member_once UNIQUE (pool_id, person_id)
);
