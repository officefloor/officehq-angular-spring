-- The sheet's holidays, each date at most once. A claim's due-by falling on one moves to the next
-- day that is not.
CREATE TABLE holiday (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id     VARCHAR(100) NOT NULL REFERENCES sheet (id),
    holiday_date DATE     NOT NULL,
    CONSTRAINT holiday_once UNIQUE (sheet_id, holiday_date)
);
