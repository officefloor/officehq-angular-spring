-- The sheet's holidays: a claim whose date plus its terms falls on one is due by the next day that is not one,
-- by the holidays on the sheet when the claim is added. A date is on a sheet's list at most once.
CREATE TABLE holiday (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id     VARCHAR(200) NOT NULL REFERENCES sheet (id),
    holiday_date DATE         NOT NULL,
    UNIQUE (sheet_id, holiday_date)
);
