-- The sheet's void reasons: while a sheet has any, a claim is voided with one of them. A reason is on a
-- sheet's list at most once. A voided claim keeps the reason it was voided with; none when voided without.
CREATE TABLE void_reason (
    id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(200) NOT NULL REFERENCES sheet (id),
    reason   VARCHAR(200) NOT NULL,
    UNIQUE (sheet_id, reason)
);

ALTER TABLE claim ADD COLUMN void_reason VARCHAR(200);
