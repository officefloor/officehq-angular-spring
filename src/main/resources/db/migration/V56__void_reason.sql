-- The sheet's void reasons, each (trimmed) text at most once. While a sheet has any, a claim is
-- voided only with one of them, kept on the claim.
CREATE TABLE void_reason (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    reason   VARCHAR(200) NOT NULL,
    CONSTRAINT void_reason_once UNIQUE (sheet_id, reason)
);

-- The reason a claim was voided with; none when voided without one, or not voided.
ALTER TABLE claim ADD COLUMN void_reason VARCHAR(200);
