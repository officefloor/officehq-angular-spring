-- A sheet assigns a role to a user name: clerk (the default for any name not listed) or steward.
CREATE TABLE sheet_role (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL REFERENCES sheet (id),
    user_name VARCHAR(100) NOT NULL,
    role      VARCHAR(20)  NOT NULL CHECK (role IN ('clerk', 'steward'))
);
CREATE UNIQUE INDEX sheet_role_sheet_user ON sheet_role (sheet_id, user_name);
-- The sheet's clerk limit: a clerk settles a claim only when its due is at or below it. Null: no limit.
ALTER TABLE sheet ADD COLUMN clerk_limit DECIMAL(14, 2) CHECK (clerk_limit >= 0);
