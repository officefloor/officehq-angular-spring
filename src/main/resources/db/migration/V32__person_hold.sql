-- A person may have several holds over time, each from a date and, optionally, to a date (both
-- inclusive). While a hold covers an OPEN or PENDING claim's date, and no statement bound it, the
-- claim counts in no live total. A person held before holds were dated keeps a hold from the
-- beginning of time (no from-date) with no end.
CREATE TABLE person_hold (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person (id),
    from_date DATE,
    to_date   DATE
);
INSERT INTO person_hold (person_id, from_date, to_date) SELECT id, NULL, NULL FROM person WHERE held;
ALTER TABLE person DROP COLUMN held;
