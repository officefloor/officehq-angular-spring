-- The workspace's volume discounts: an invoice whose subtotal is over a threshold (in US dollars,
-- converted to the client's currency at the issue date's rate, rounded down) gets the percentage of
-- the highest threshold it passes as its discount when that is more than its own.
CREATE TABLE volume_discount (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    over_usd DECIMAL(19, 2) NOT NULL,
    pct      DECIMAL(5, 2)  NOT NULL
);
