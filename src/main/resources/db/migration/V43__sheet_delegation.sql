-- A steward's delegation of the steward role to a user for a from-date to a to-date, inclusive, by
-- the sheet's today. Listed in the order they were made (by id).
CREATE TABLE sheet_delegation (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id   VARCHAR(100) NOT NULL REFERENCES sheet (id),
    user_name  VARCHAR(100) NOT NULL,
    from_date  DATE         NOT NULL,
    to_date    DATE         NOT NULL,
    steward    VARCHAR(100) NOT NULL,
    CHECK (to_date >= from_date)
);
CREATE INDEX sheet_delegation_sheet ON sheet_delegation (sheet_id, user_name);
