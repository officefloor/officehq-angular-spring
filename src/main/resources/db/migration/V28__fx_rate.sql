-- Dated exchange rates: from a date on, the US dollars one unit of the currency is worth. Something
-- converted on a date uses the latest dated rate on or before it, or the standing usd_per_<code>
-- setting before any.
CREATE TABLE fx_rate (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_date DATE           NOT NULL,
    currency  VARCHAR(3)     NOT NULL,
    usd_per   DECIMAL(19, 8) NOT NULL
);
