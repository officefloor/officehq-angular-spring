-- A rate is kept as versions: setting a grade's rate for a from-date it already has keeps the value
-- it replaces as an older version. The rate row holds the newest (the one in force) and how many
-- versions it has had; each older one is kept here with its number.
ALTER TABLE rate ADD COLUMN version INT DEFAULT 1 NOT NULL CHECK (version >= 1);
CREATE TABLE rate_version (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL REFERENCES sheet (id),
    grade     VARCHAR(1)   NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    from_date DATE,
    to_date   DATE,
    pct       DECIMAL(5, 2) NOT NULL CHECK (pct >= 0),
    version   INT NOT NULL
);
CREATE INDEX rate_version_sheet ON rate_version (sheet_id, grade, from_date);
