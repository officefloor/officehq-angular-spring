-- A rate is kept as versions: setting a grade's rate for a from-date it already has keeps the value it
-- replaces as an older version and makes the new one the rate in force. The rate row holds the newest
-- version and how many versions it has had (1 for a rate never replaced); its older versions are kept
-- here, oldest first (by version).
ALTER TABLE rate ADD COLUMN version INTEGER DEFAULT 1 NOT NULL CHECK (version >= 1);
CREATE TABLE rate_version (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_id    BIGINT        NOT NULL REFERENCES rate (id),
    version    INTEGER       NOT NULL,
    rate       DECIMAL(9, 2) NOT NULL,
    to_date    DATE,
    set_by     VARCHAR(200)
);
CREATE UNIQUE INDEX rate_version_rate ON rate_version (rate_id, version);
