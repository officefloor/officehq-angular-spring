-- A person's past retirements: each one they were unretired from, from the date they were retired from
-- to the day they were unretired. A claim dated after the from and before the to of one is refused.
CREATE TABLE person_retirement (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person (id),
    from_date DATE NOT NULL,
    to_date   DATE NOT NULL
);
