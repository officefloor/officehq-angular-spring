-- A person may have aliases, each stored trimmed. An alias shares the names' uniqueness on the sheet,
-- compared without regard to case: alias_key is the alias as compared, and the index refuses a second
-- alias with it (an alias equal to a name is refused by the service).
CREATE TABLE person_alias (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200) NOT NULL,
    person_id BIGINT NOT NULL REFERENCES person (id),
    alias     VARCHAR(200) NOT NULL,
    alias_key VARCHAR(200) GENERATED ALWAYS AS (LOWER(alias))
);
CREATE UNIQUE INDEX person_alias_sheet_key ON person_alias (sheet_id, alias_key);
CREATE INDEX person_alias_person ON person_alias (person_id);
