-- A person's grade is dated: each grade they are given applies from a date, the first from the
-- beginning of time (no from-date). On a date the grade in force is the one whose from-date is the
-- latest on or before it. A person has at most one grade per from-date (and one with none).
CREATE TABLE person_grade (
    id        BIGINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT     NOT NULL REFERENCES person (id),
    grade     VARCHAR(1) NOT NULL CHECK (grade IN ('A', 'B', 'C')),
    from_date DATE,
    from_key  DATE GENERATED ALWAYS AS (COALESCE(from_date, DATE '0001-01-01'))
);
CREATE UNIQUE INDEX person_grade_from ON person_grade (person_id, from_key);
INSERT INTO person_grade (person_id, grade, from_date) SELECT id, grade, NULL FROM person;
ALTER TABLE person DROP COLUMN grade;
