-- The sheet as it stood after each change: every stored row of the sheet, taken once the change is
-- made, with the sheet's today then (made_on; none for the empty sheet first loaded, which counts
-- from the beginning of time). An as-of view shows the last one made on or before its date.
CREATE TABLE sheet_snapshot (
    seq      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    made_on  DATE,
    data     BLOB         NOT NULL
);
CREATE INDEX sheet_snapshot_sheet ON sheet_snapshot (sheet_id, seq);
