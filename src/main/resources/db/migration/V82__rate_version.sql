-- A rate is kept as versions: setting a rate for a grade and from-date that already has one keeps the value it
-- replaces as an older version. The rate row holds the newest version (the one in force) and its number.
ALTER TABLE rate ADD COLUMN version INT NOT NULL DEFAULT 1 CHECK (version >= 1);
CREATE TABLE rate_version (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_id BIGINT        NOT NULL REFERENCES rate (id),
    version INT           NOT NULL,
    rate    DECIMAL(5, 2) NOT NULL CHECK (rate >= 0),
    to_date DATE,
    CONSTRAINT rate_version_rate_version UNIQUE (rate_id, version)
);
