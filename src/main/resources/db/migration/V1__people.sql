-- People on the sheet. alpha, beta and gamma are optional whole numbers (NULL = left blank).
CREATE TABLE person (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL DEFAULT '',
    alpha INTEGER,
    beta  INTEGER,
    gamma INTEGER,
    hold  BOOLEAN NOT NULL DEFAULT FALSE
);

-- A person's patrons: other people on the sheet.
CREATE TABLE person_patron (
    person_id BIGINT NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    patron_id BIGINT NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    PRIMARY KEY (person_id, patron_id)
);
