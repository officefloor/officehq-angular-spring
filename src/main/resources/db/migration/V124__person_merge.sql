-- Each merge of one person into another made on the sheet: whom into whom, who made it and on which
-- sheet-today, whether it has been undone, the merged person as they stood before it (none when it cannot
-- be undone) and the claims that came from them, so the last merge into a person can be undone.
CREATE TABLE person_merge (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(200)  NOT NULL REFERENCES sheet (id),
    from_id   BIGINT        NOT NULL,
    into_id   BIGINT        NOT NULL,
    made_by   VARCHAR(200)  NOT NULL,
    made_on   DATE          NOT NULL,
    state     CLOB,
    undone    BOOLEAN       DEFAULT FALSE NOT NULL
);
CREATE INDEX person_merge_into ON person_merge (sheet_id, into_id, id);
CREATE TABLE person_merge_claim (
    merge_id BIGINT NOT NULL REFERENCES person_merge (id),
    claim_id BIGINT NOT NULL,
    PRIMARY KEY (merge_id, claim_id)
);
