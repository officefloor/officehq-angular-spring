-- The merges into a person, kept so the steward who made one can undo it on the same sheet-today:
-- who was merged into whom, by whom and on which today, the claims that moved, and the merged
-- person's own rows (person and its person tables) as they stood, to be put back under their id.
CREATE TABLE person_merge (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id  VARCHAR(100) NOT NULL REFERENCES sheet (id),
    from_id   BIGINT       NOT NULL,
    into_id   BIGINT       NOT NULL,
    merged_by VARCHAR(100) NOT NULL,
    merged_on DATE         NOT NULL,
    claim_ids VARCHAR(100000) NOT NULL,
    data      VARBINARY(10000000) NOT NULL
);
CREATE INDEX person_merge_into ON person_merge (sheet_id, into_id, id);
