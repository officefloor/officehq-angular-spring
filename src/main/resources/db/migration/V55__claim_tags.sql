-- A claim's tags: trimmed, lower-cased, without repeats, sorted and comma separated; none when not given.
ALTER TABLE claim ADD COLUMN tags VARCHAR(500);

-- Every tag ever used on a sheet: kept once a claim carries it, so the sheet shows its due-total
-- even when no claim carries it any more.
CREATE TABLE claim_tag_used (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(100) NOT NULL REFERENCES sheet (id),
    tag      VARCHAR(500) NOT NULL,
    CONSTRAINT claim_tag_used_unique UNIQUE (sheet_id, tag)
);
