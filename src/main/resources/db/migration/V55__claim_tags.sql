-- A claim's tags: trimmed, lower-cased, without repeats, sorted and comma separated; none when not given.
ALTER TABLE claim ADD COLUMN tags VARCHAR(2000);

-- Every tag ever used on a sheet's claims, once each: the sheet shows a due-total for each.
CREATE TABLE sheet_tag (
    id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id VARCHAR(200) NOT NULL REFERENCES sheet (id),
    tag      VARCHAR(2000) NOT NULL,
    UNIQUE (sheet_id, tag)
);
