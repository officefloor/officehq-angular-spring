-- A snapshot of a person's due-total, written as the sheet's today moves on: the day being left and their
-- due-total then (none when it was n/a). Listed oldest first (by id).
CREATE TABLE person_snapshot (
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id    VARCHAR(200)   NOT NULL REFERENCES sheet (id),
    person_id   BIGINT         NOT NULL REFERENCES person (id),
    left_on     DATE           NOT NULL,
    due_total   DECIMAL(15, 2)
);
CREATE INDEX person_snapshot_person ON person_snapshot (person_id, id);
CREATE INDEX person_snapshot_sheet ON person_snapshot (sheet_id, id);
