-- Sheet-wide numbering restarts each fiscal year: a claim opened is numbered FY<year>-<n> within the fiscal
-- year (by the sheet's fiscal start month) of its due-by, the sequence shared across the sheet's tree.
-- The last number each sheet gave in each fiscal year; the next is one past the highest across the tree.
-- Numbers already given stay.
CREATE TABLE fiscal_claim_sequence (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id    VARCHAR(200) NOT NULL REFERENCES sheet (id),
    fiscal_year INT          NOT NULL,
    last_number INT          NOT NULL
);
CREATE UNIQUE INDEX fiscal_claim_sequence_year ON fiscal_claim_sequence (sheet_id, fiscal_year);
